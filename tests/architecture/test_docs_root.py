#: The size of `LIVING_AT_THE_ROOT`. Lower it when a document leaves the list; raising it is
#: the growth the list refuses.
LIVING_AT_THE_ROOT_SIZE = 106


def _root_files() -> list[str]:
    """Every file directly under `docs/`, by name."""

    return sorted(
        posixpath.basename(path)
        for path in _listed_paths()
        if posixpath.dirname(path) == "docs" and (REPOSITORY_ROOT / path).is_file()
    )


def _kind(name: str, json_stems: frozenset[str]) -> str:
    """What a file directly under `docs/` is, by its name and the names beside it."""

    if name == "README.md":
        return "guide"
    stem, extension = posixpath.splitext(name)
    if extension == ".json":
        return "record"
    if extension == ".md" and (stem in json_stems or name in TWINLESS_RECORDS_PINNED_BY_NAME):
        return "record"
    if name.endswith(("_prereg.md", "_protocol.md")):
        return "pre-registration"
    return "living"


def _living_at_the_root() -> set[str]:
    files = _root_files()
    json_stems = frozenset(posixpath.splitext(name)[0] for name in files if name.endswith(".json"))
    return {name for name in files if _kind(name, json_stems) == "living"}


def test_no_new_living_document_is_written_at_the_docs_root() -> None:
    new = sorted(_living_at_the_root() - LIVING_AT_THE_ROOT)

    assert not new, "\n".join(
        [
            "A living document was added directly under docs/. Put it in the folder of its",
            f"readers ({', '.join(f'docs/{home}/' for home in HOMES)}) and link it from that",
            "folder's guide. A record has its JSON beside it, and a pre-registration ends in",
            "_prereg.md:",
            *new,
        ]
    )


def test_the_list_of_living_documents_at_the_root_only_shrinks() -> None:
    gone = sorted(LIVING_AT_THE_ROOT - _living_at_the_root())

    assert not gone, "\n".join(
        [
            "A document on LIVING_AT_THE_ROOT is no longer a living document at the root of",
            "docs/ (it moved, was removed or became a record). Remove it from the list:",
            *gone,
        ]
    )


def test_the_list_of_living_documents_at_the_root_keeps_its_size() -> None:
    assert len(LIVING_AT_THE_ROOT) == LIVING_AT_THE_ROOT_SIZE, (
        "the list only shrinks: when a document leaves it, lower LIVING_AT_THE_ROOT_SIZE"
    )


def test_every_home_for_a_new_document_has_a_guide() -> None:
    listed = set(_listed_paths())

    assert [home for home in HOMES if f"docs/{home}/README.md" not in listed] == []


def test_a_file_is_living_only_when_it_is_nothing_else() -> None:
    """The naming rule is exercised on synthetic names, so a drift in it is seen here."""

    json_stems = frozenset({"benchmark_v2", "fw10_frozen_candidate"})

    assert _kind("README.md", json_stems) == "guide"
    assert _kind("benchmark_v2.json", json_stems) == "record"
    assert _kind("benchmark_v2.md", json_stems) == "record"
    assert _kind("weekly_scorecard.md", json_stems) == "record"
    assert _kind("benchmark_v2_prereg.md", json_stems) == "pre-registration"
    assert _kind("lookahead_budget_protocol.md", json_stems) == "pre-registration"
    assert _kind("weekly_runbook.md", json_stems) == "living"
    assert _kind("fw10_holdout_note.md", json_stems) == "living"
    assert _kind("checklist.txt", json_stems) == "living"
