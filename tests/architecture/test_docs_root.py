"""No new living document is written directly under `docs/`; it goes in the folder of its readers.

The root of `docs/` is one flat folder of 373 files. Most of them stay there on purpose: 115
JSON records, the 105 Markdown twins beside them, two Markdown records that
`tests/architecture/test_measurements_index.py` pins by name, and 44 pre-registrations. Runners,
tests and other records cite their paths, some inside generated bytes, so a move is a code
change (ADR 0003, rule 5). Beside them sit 106 living documents: runbooks, specifications,
notes, contracts in prose and plans. A reader looking for a runbook or a specification has to
find it among the records, and every new living document written at the root makes that harder.

So the living documents at the root are frozen here as a list that only shrinks. A new one
goes in the folder of its readers (`architecture/`, `operations/`, `product/`, `research/` or
`specs/`), each of which has a guide that links it. A document leaves the list when it is
moved or retired; nothing here requires that, and a move is a change to every link and
citation of the old path in the same pull request. `LIVING_AT_THE_ROOT_SIZE` pins the size of
the list, so a name cannot join it without changing a number a reviewer sees.

What counts as living is what is not something else, by name:

- a record: a JSON file, a Markdown file with a JSON file of the same stem beside it, or one
  of the two pinned Markdown records;
- a pre-registration: a file ending in `_prereg.md` or `_protocol.md`;
- the folder's own guide, `docs/README.md`.

Everything else directly under `docs/` is living, whatever its extension. The files are what
git lists there (tracked, or untracked and not ignored) and that exist on disk, so a document
written but not yet added is checked while its pull request is being prepared.
"""

